/**
 * The context layer: a deterministic, source-cited digest of everything known about one experiment plan or one contract.
 * The assistant, the dashboard and the MCP server all read this same object, so they cannot disagree. Nothing in it is
 * generated by a model; each fact comes from a stored record or a live read, and `fingerprint` changes only when a fact
 * that matters for a decision changes.
 */

export type Scope = { type: "plan" | "contract"; id: string };

export interface Change { field: string; then: unknown; now: unknown }
export interface Brief {
  scope: Scope;
  generatedAt: number;
  source: "real" | "simulation";
  title: string;
  facts: Record<string, unknown>;
  /** The small, stable subset of facts that a decision depends on. */
  keyFacts: Record<string, unknown>;
  fingerprint: string;
  integrity: { ok: boolean; entries: number; head: string | null; reason: string | null };
  officialDecision: { seq: number; decision: string; rationale: string; approvedBy: string; proposedBy: string; at: number; resolutionSeq: number } | null;
  pendingProposals: { seq: number; decision: string; rationale: string; proposedBy: string; at: number; stale: boolean }[];
  changedSinceOfficialDecision: Change[];
  openQuestions: string[];
  recent: { seq: number; ts: number; kind: string; actor: string; summary: string }[];
}

const flat = (o: unknown, prefix = "", out: Record<string, unknown> = {}): Record<string, unknown> => {
  if (o !== null && typeof o === "object" && !Array.isArray(o)) { for (const [k, v] of Object.entries(o as Record<string, unknown>)) flat(v, prefix ? `${prefix}.${k}` : k, out); }
  else out[prefix] = o;
  return out;
};

export function diffKeyFacts(then: Record<string, unknown>, now: Record<string, unknown>): Change[] {
  const a = flat(then), b = flat(now), out: Change[] = [];
  for (const k of [...new Set([...Object.keys(a), ...Object.keys(b)])].sort()) if (JSON.stringify(a[k] ?? null) !== JSON.stringify(b[k] ?? null)) out.push({ field: k, then: a[k] ?? null, now: b[k] ?? null });
  return out;
}

const fp = (keyFacts: Record<string, unknown>): string => createHash("sha256").update(canonicalJson(keyFacts)).digest("hex").slice(0, 16);

export function snapshotOf(b: Brief): Snapshot { return { fingerprint: b.fingerprint, facts: b.keyFacts, generatedAt: b.generatedAt }; }

function contractFacts(ctx: Ctx, contractId: string): Record<string, unknown> {
  const r = buildReport(ctx, contractId);
  const sev = (s: string): number => r.report.findings.filter((f) => f.severity === s).length;
  return { id: contractId, version: r.report.version, status: r.report.status, primaryCode: r.report.primaryCode, errors: sev("error"), warnings: sev("warning"), unlinkedObservations: r.report.unlinkedObservations, subjects: r.subjectsTotal };
}

async function planBrief(ctx: Ctx, plan: Plan): Promise<Pick<Brief, "title" | "facts" | "keyFacts" | "source" | "openQuestions">> {
  const src = plan.isSimulation ? "simulation" : "real";
  const v = await verdictFor(ctx, plan, src);
  const evidence = ctx.db.all("SELECT id, created_at, payload FROM evidence WHERE plan_id = ? ORDER BY id DESC", plan.id);
  // The newest stored snapshot. Live windows roll and empty out (a paused experiment has no new traffic), so the last snapshot is
  // what the assistant must fall back on instead of treating "no recent data" as "all clear".
  let latestEvidence: { id: number; at: number; outcome: string | null; headline: string | null } | null = null;
  if (evidence[0]) {
    let snap: { verdict?: { outcome?: string; headline?: string } } = {};
    try { snap = JSON.parse(String(evidence[0].payload)) as typeof snap; } catch { /* reported as unknown outcome */ }
    latestEvidence = { id: Number(evidence[0].id), at: Number(evidence[0].created_at), outcome: snap.verdict?.outcome ?? null, headline: snap.verdict?.headline ?? null };
  }
  // A contract belongs to a plan when it checks the same Flagsmith flag the plan experiments on.
  const contracts = listContracts(ctx).filter((c) => !c.isSimulation === !plan.isSimulation && plan.featureKey !== "").flatMap((c) => {
    try { return getContractVersion(ctx, c.id).contract.experiment.assignmentFlag === plan.featureKey ? [contractFacts(ctx, c.id)] : []; } catch { return []; }
  });
  const variants = v.verdict.reliabilityVerdict.variants.map((x) => ({ variant: x.variantKey, status: x.status, breached: x.metrics.filter((m) => m.status === "BREACH").map((m) => m.metric) }));
  const facts = {
    plan: { id: plan.id, key: plan.key, owner: plan.owner, hypothesis: plan.hypothesis, featureKey: plan.featureKey, controlVariant: plan.controlVariant, treatmentVariants: plan.treatmentVariants, acceptanceCriteria: plan.acceptanceCriteria },
    approval: plan.approval,
    flagsmith: { linked: plan.flagsmithExperimentId !== null, experimentId: plan.flagsmithExperimentId, status: v.flagsmithStatus, error: v.flagsmithError?.message ?? null, resultsAsOf: v.resultsAsOf },
    verdict: { outcome: v.verdict.outcome, headline: v.verdict.headline, recommendedAction: v.verdict.recommendedAction, experimentState: v.verdict.experimentVerdict.state, winner: v.verdict.experimentVerdict.winner, reliabilityStatus: v.verdict.reliabilityVerdict.status, evidence: v.verdict.evidence, caveats: v.verdict.caveats },
    variants,
    bench: benchSummary(ctx),
    evidence: { count: evidence.length, latestId: evidence[0] ? Number(evidence[0].id) : null, latest: latestEvidence },
    contracts,
  };
  const keyFacts = {
    outcome: v.verdict.outcome, reliability: v.verdict.reliabilityVerdict.status, experimentState: v.verdict.experimentVerdict.state, winner: v.verdict.experimentVerdict.winner,
    flagsmithStatus: v.flagsmithStatus, planApproval: plan.approval.status,
    variants: Object.fromEntries(variants.map((x) => [x.variant, x.status])),
    contracts: Object.fromEntries(contracts.map((c) => [String(c.id), `${c.status}`])),
  };
  const q: string[] = [];
  if (evidence.length === 0) q.push("No evidence snapshot has been captured for this plan.");
  if (plan.approval.status === "pending") q.push("The plan itself is still awaiting approval.");
  if (plan.flagsmithExperimentId === null && !plan.isSimulation) q.push("The plan is not linked to a Flagsmith experiment, so there is no Flagsmith verdict.");
  if (v.flagsmithError) q.push(`Flagsmith data was unavailable: ${v.flagsmithError.message}`);
  if (v.verdict.outcome === "INSUFFICIENT_EVIDENCE") q.push("There is not yet enough data for either verdict.");
  for (const c of contracts) if (c.status === "NO_DATA") q.push(`Contract ${String(c.id)} has received no observations.`);
  return { title: plan.title, facts, keyFacts, source: src, openQuestions: q };
}

function contractBrief(ctx: Ctx, id: string): Pick<Brief, "title" | "facts" | "keyFacts" | "source" | "openQuestions"> {
  const stored = getContractVersion(ctx, id);
  const r = buildReport(ctx, id);
  const open = r.report.findings.filter((f) => f.severity !== "info").slice(0, 25).map((f) => ({ code: f.code, severity: f.severity, surfaceId: f.surfaceId, subjectRef: f.subjectRef, message: f.message, dedupeKey: f.dedupeKey }));
  const codes: Record<string, number> = {};
  for (const f of r.report.findings) if (f.severity !== "info") codes[f.code] = (codes[f.code] ?? 0) + 1;
  const facts = {
    contract: { id, version: r.report.version, experimentKey: stored.contract.experiment.key, assignmentFlag: stored.contract.experiment.assignmentFlag, environment: stored.contract.experiment.environment, surfaces: stored.contract.surfaces.map((s) => s.id) },
    status: r.report.status, primaryCode: r.report.primaryCode, observations: { linked: r.report.linkedObservations, unlinked: r.report.unlinkedObservations, latestAt: r.report.latestObservationAtMs },
    surfaces: r.report.surfaces.map((s) => ({ id: s.id, status: s.status, subjects: s.subjects, errors: s.errors, warnings: s.warnings })), findingsByCode: codes, openFindings: open,
    drift: r.drift.length, versions: r.versions, subjects: r.subjectsTotal,
  };
  const keyFacts = { status: r.report.status, primaryCode: r.report.primaryCode, version: r.report.version, surfaces: Object.fromEntries(r.report.surfaces.map((s) => [s.id, s.status])), findingsByCode: codes };
  const q: string[] = [];
  if (r.report.status === "NO_DATA") q.push("No surface has reported an observation in the correlation window.");
  if (r.report.unlinkedObservations > 0) q.push(`${r.report.unlinkedObservations} observation(s) carried no verifiable identity and were excluded.`);
  return { title: id, facts, keyFacts, source: stored.isSimulation ? "simulation" : "real", openQuestions: q };
}

const brief = (e: LedgerEntry): Brief["recent"][number] => ({ seq: e.seq, ts: e.ts, kind: e.kind, actor: e.actor, summary: e.summary });

export async function buildBrief(ctx: Ctx, scope: Scope): Promise<Brief> {
  let part: Pick<Brief, "title" | "facts" | "keyFacts" | "source" | "openQuestions">;
  if (scope.type === "plan") { const n = Number(scope.id); if (!Number.isInteger(n) || n < 1) throw new HttpError(400, "validation_failed", "plan id must be a positive integer"); part = await planBrief(ctx, getPlan(ctx, n)); }
  else if (scope.type === "contract") part = contractBrief(ctx, scope.id);
  else throw new HttpError(400, "validation_failed", 'scope.type must be "plan" or "contract"');
  const fingerprint = fp(part.keyFacts);
  const st = scope.type as SubjectType;
  const official = latestOfficialDecision(ctx, st, scope.id);
  const decisions = decisionsFor(ctx, st, scope.id);
  const officialDecision = official ? {
    seq: official.proposal.seq, decision: String(official.proposal.payload.decision), rationale: String(official.proposal.payload.rationale), approvedBy: official.resolution!.actor, proposedBy: official.proposal.actor,
    at: official.resolution!.ts, resolutionSeq: official.resolution!.seq,
  } : null;
  const pendingProposals = decisions.filter((d) => d.status === "proposed").map((d) => ({
    seq: d.proposal.seq, decision: String(d.proposal.payload.decision), rationale: String(d.proposal.payload.rationale), proposedBy: d.proposal.actor, at: d.proposal.ts,
    stale: (d.proposal.payload.snapshot as Snapshot | undefined)?.fingerprint !== fingerprint,
  }));
  const thenFacts = official ? ((official.resolution!.payload.snapshot as Snapshot | undefined)?.facts ?? {}) : null;
  const changed = thenFacts ? diffKeyFacts(thenFacts, part.keyFacts) : [];
  const v = verifyLedger(ctx);
  const questions = [...part.openQuestions];
  if (!official) questions.push("No official decision has been recorded.");
  if (official && changed.length) questions.push(`${changed.length} fact(s) changed since the official decision (#${official.proposal.seq}).`);
  if (!v.ok) questions.push(`The decision ledger failed verification at entry ${v.firstBadSeq}: ${v.reason}`);
  return {
    scope, generatedAt: ctx.now(), source: part.source, title: part.title, facts: part.facts, keyFacts: part.keyFacts, fingerprint,
    integrity: { ok: v.ok, entries: v.entries, head: v.head, reason: v.reason }, officialDecision, pendingProposals, changedSinceOfficialDecision: changed, openQuestions: questions,
    recent: listEntries(ctx, { subjectType: scope.type, subjectId: scope.id, limit: 12 }).map(brief),
  };
}
